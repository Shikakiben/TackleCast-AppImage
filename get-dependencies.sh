#!/bin/sh

set -eu

ARCH=$(uname -m)

echo "Installing build dependencies..."
echo "---------------------------------------------------------------"
# TackleCast has no Arch package and no prebuilt Linux archive we can reuse, so
# it is built from source, following upstream's BUILD.md recipe.
# - rust/cargo, clang (bindgen for ffmpeg-sys-next), nasm (FFmpeg)
# - alsa-lib: cpal links libasound
# - base-devel/diffutils: make and cmp needed by the FFmpeg configure+make recipe
# - libxkbcommon-x11: winit dlopen()s it on X11. quick-sharun only deploys what
#   is installed, so missing it here means the packaged AppImage panics with
#   "Library libxkbcommon-x11.so could not be loaded." (measured)
# - libxi/libxcursor/libxrandr/libxinerama: also dlopen()ed by winit
# - xorg-server-xvfb: quick-sharun --test and the smoke test run headless
# - vulkan-swrast: provides lavapipe, the software Vulkan ICD. It must be
#   installed at BUILD time, otherwise quick-sharun cannot deploy it and
#   DEPLOY_VULKAN_ALL has nothing to bundle (measured: without it the packaged
#   AppImage fails with "renderer initialization failed ... Parent device is
#   lost" because only the GL-indirect virtio ICD is available).
# - patch, git: source checkout and the two patches
pacman -Syu --noconfirm \
	base-devel \
	rust \
	clang \
	nasm \
	pkgconf \
	alsa-lib \
	libxi \
	libxcursor \
	libxrandr \
	libxinerama \
	libxkbcommon-x11 \
	vulkan-icd-loader \
	vulkan-swrast \
	patch \
	git \
	xorg-server-xvfb \
	xz \
	curl \
	wget

echo "Installing debloated packages..."
echo "---------------------------------------------------------------"
# Note: llvm-libs is deliberately kept as-is (not debloated), the same reason
# Alacritty-AppImage does it: the debloated LLVM makes rustc fail with
# "undefined symbol: LLVMInitializeARMTargetInfo".
get-debloated-pkgs --add-common --prefer-nano ! llvm-libs

# NOTE: do NOT install the `ffmpeg` package. Arch ships FFmpeg 9, while
# ffmpeg-next 8.1.0 only supports FFmpeg 8.x (FFmpeg 9 removed AVCodec fields
# and codec IDs the bindings still reference -> 14 build errors). Upstream's
# pinned FFmpeg 8.1.3 is built below by setup_linux_dependencies.sh instead.

echo "Fetching TackleCast..."
echo "---------------------------------------------------------------"
VERSION=$(cat ./LATEST_VERSION)
REPO=https://github.com/SaltedByte/TackleCast.git

# The tag is preferred (reproducible); fall back to main if upstream ever drops
# a tag, as anylinux-setup-action templates commonly do.
if ! git clone --depth 1 --branch "v$VERSION" "$REPO" ./src; then
	echo "Tag v$VERSION not found, falling back to main" >&2
	git clone --depth 1 "$REPO" ./src
fi
echo "$VERSION" > ~/version

echo "Building TackleCast $VERSION..."
echo "---------------------------------------------------------------"
# Upstream pins FFmpeg 8.1.3 (sha256 verified by their script).
#
# The archive is downloaded here first, with retries: upstream's script uses a
# single `curl --fail` with no retry, and ffmpeg.org drops connections
# intermittently (reproduced: "curl: (35) Recv failure: Connection reset by
# peer"). Their script reuses an already-present archive.
FFMPEG_TARBALL=./src/.deps/ffmpeg-8.1.3.tar.xz
if [ ! -f "$FFMPEG_TARBALL" ]; then
	mkdir -p ./src/.deps
	for attempt in 1 2 3 4 5; do
		if curl -L --fail --retry 5 --retry-all-errors -C - \
			-o "$FFMPEG_TARBALL" \
			https://ffmpeg.org/releases/ffmpeg-8.1.3.tar.xz; then
			break
		fi
		echo "FFmpeg download attempt $attempt failed, retrying..." >&2
		sleep 5
	done
fi
[ -f "$FFMPEG_TARBALL" ]

bash ./src/scripts/setup_linux_dependencies.sh

export FFMPEG_DIR="$PWD/src/.deps/ffmpeg"
export PKG_CONFIG_PATH="$FFMPEG_DIR/lib/pkgconfig${PKG_CONFIG_PATH:+:$PKG_CONFIG_PATH}"
export LD_LIBRARY_PATH="$FFMPEG_DIR/lib${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}"

# quick-sharun runs `ldd` on the binary, so the pinned FFmpeg must be resolvable
# through the normal linker search path.
cp -a "$FFMPEG_DIR"/lib/libav* "$FFMPEG_DIR"/lib/libsw* /usr/lib/
ldconfig

echo "Applying patches..."
echo "---------------------------------------------------------------"
patch -p1 -d ./src < ./patches/0001-xdg-settings-and-logs.patch
patch -p1 -d ./src < ./patches/0002-linux-window-icon.patch
patch -p1 -d ./src < ./patches/0003-vulkan-only-backend.patch

# Fail loudly if upstream drift makes a patch silently useless.
grep -q 'fn xdg_base_dir' ./src/src/settings.rs
grep -q 'pub fn logs_path' ./src/src/settings.rs
grep -q 'crate::settings::logs_path' ./src/src/logger.rs
grep -q 'fn set_window_icon' ./src/src/main.rs
grep -q 'set_window_icon(&window)' ./src/src/main.rs
grep -q 'wgpu::Backends::VULKAN' ./src/src/render.rs

# Keep upstream's own quality gate: a broken patch must never reach a release.
(cd ./src && cargo fmt --all --check)

# `cargo clean` is deliberate: FFmpeg bindings generated by an earlier build
# stay in target/ and would link the binary against libavcodec.so.63, which does
# not exist here (measured: the binary then dies with "cannot open shared
# object file: libavcodec.so.63").
(cd ./src && cargo clean && cargo build --release --locked)

BIN=./src/target/release/tacklecast
[ -x "$BIN" ]

# Assert the binary links the pinned FFmpeg 8 and not a system FFmpeg 9.
readelf -d "$BIN" | grep -q 'libavcodec\.so\.62'
if readelf -d "$BIN" | grep -qE 'libavcodec\.so\.(6[3-9]|[7-9][0-9])'; then
	echo "ERROR: binary links the wrong libavcodec (expected FFmpeg 8 / .so.62)" >&2
	exit 1
fi

echo "Placing binary, desktop file and icon in /usr..."
echo "---------------------------------------------------------------"
# Upstream ships no `make install`, no .desktop file and no arch install: its
# own Linux package is a tarball with lib/ plus run.sh. So the install step is
# ours, and it belongs here rather than in make-appimage.sh: this mirrors what
# a distro package would do, and lets make-appimage.sh stay a plain
# "ICON=/usr/share/... quick-sharun /usr/bin/tacklecast".
install -Dm755 "$BIN" /usr/bin/tacklecast
# Upstream's icon is 500x500, so it is not installed under a hicolor/512x512
# name it does not match; pixmaps/ is the standard place for a single PNG.
install -Dm644 ./tacklecast.png /usr/share/pixmaps/tacklecast.png
install -Dm644 ./tacklecast.desktop /usr/share/applications/tacklecast.desktop
install -Dm644 ./LICENSE /usr/share/licenses/tacklecast/LICENSE
